import { beforeEach, describe, expect, it, vi } from 'vitest'
import { apiClient } from '@/lib/api-client'
import { systemApi } from './system-api'

vi.mock('@/lib/api-client', () => ({
  apiClient: {
    get: vi.fn(),
    put: vi.fn(),
  },
}))

describe('systemApi identity', () => {
  beforeEach(() => {
    vi.clearAllMocks()
  })

  it('getIdentity() parses the device identity projection', async () => {
    vi.mocked(apiClient.get).mockResolvedValueOnce({
      data: {
        code: 'OK',
        message: 'ok',
        data: {
          deviceId: 'site-a-gate-01',
          autoGenerated: false,
          updatedAt: '2026-11-05T08:00:00Z',
        },
      },
    })

    const identity = await systemApi.getIdentity()

    expect(identity.deviceId).toBe('site-a-gate-01')
    expect(identity.autoGenerated).toBe(false)
    expect(apiClient.get).toHaveBeenCalledWith('/system/identity')
  })

  it('updateIdentity() sends the new id and parses the result', async () => {
    vi.mocked(apiClient.put).mockResolvedValueOnce({
      data: {
        code: 'OK',
        message: 'ok',
        data: {
          deviceId: 'site-b-02',
          autoGenerated: false,
          updatedAt: '2026-11-05T09:00:00Z',
        },
      },
    })

    const identity = await systemApi.updateIdentity('site-b-02')

    expect(identity.deviceId).toBe('site-b-02')
    expect(apiClient.put).toHaveBeenCalledWith('/system/identity', {
      deviceId: 'site-b-02',
    })
  })
})
