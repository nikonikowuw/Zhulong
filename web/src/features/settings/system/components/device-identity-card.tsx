import { useState } from 'react'
import { Fingerprint, Loader2, Save } from 'lucide-react'
import { useTranslation } from 'react-i18next'
import { toast } from 'sonner'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { Skeleton } from '@/components/ui/skeleton'
import {
  useSystemIdentity,
  useUpdateSystemIdentity,
} from '../hooks/use-system-identity'
import type { SystemIdentity } from '../types'

/**
 * 设备标识配置卡片。
 *
 * 这个值会写进每一条推送出去的告警 / 识别事件（payload.device_id），
 * 是汇聚平台区分「哪台边缘主机」的唯一稳定键：主机名在刷机镜像里常常是重复的，
 * 所以这里必须允许运维手工改成现场编号。
 */
export function DeviceIdentityCard() {
  const { t } = useTranslation('system')
  const { data: identity, isLoading, error } = useSystemIdentity()

  return (
    <div className='rounded-xl border bg-card/60 p-4 shadow-xs backdrop-blur-xs'>
      <div className='flex flex-col gap-4 lg:flex-row lg:items-start lg:justify-between'>
        <div className='space-y-1.5'>
          <div className='flex flex-wrap items-center gap-2'>
            <Fingerprint className='size-4 text-primary' />
            <span className='text-sm font-medium'>
              {t('identity.title', { defaultValue: '设备标识' })}
            </span>
            {identity && (
              <Badge
                variant={identity.autoGenerated ? 'secondary' : 'default'}
                className='px-1.5 py-0 text-[11px]'
              >
                {identity.autoGenerated
                  ? t('identity.autoGenerated', {
                      defaultValue: '系统自动生成',
                    })
                  : t('identity.custom', { defaultValue: '自定义' })}
              </Badge>
            )}
          </div>
          <p className='max-w-xl text-xs leading-relaxed text-muted-foreground'>
            {t('identity.desc', {
              defaultValue:
                '该编号会写进每一条推送到 Webhook / MQTT 的事件（device_id），汇聚平台据此区分事件来自哪台边缘主机。建议改成现场编号，例如 site-a-gate-01。',
            })}
          </p>
        </div>

        {isLoading ? (
          <Skeleton className='h-9 w-full rounded-md lg:w-[360px]' />
        ) : identity ? (
          // key 让表单在服务端值变化时重新挂载，避免在 effect 里同步 state。
          <IdentityForm key={identity.deviceId} identity={identity} />
        ) : (
          <p className='text-xs text-destructive'>
            {error instanceof Error
              ? error.message
              : t('identity.loadFailed', { defaultValue: '设备标识读取失败' })}
          </p>
        )}
      </div>
    </div>
  )
}

function IdentityForm({ identity }: { identity: SystemIdentity }) {
  const { t } = useTranslation('system')
  const updateIdentity = useUpdateSystemIdentity()
  const [deviceId, setDeviceId] = useState(identity.deviceId)

  const trimmed = deviceId.trim()
  const dirty = trimmed !== identity.deviceId
  const canSave = dirty && trimmed.length > 0 && !updateIdentity.isPending

  const handleSave = async () => {
    if (!canSave) {
      return
    }
    try {
      await updateIdentity.mutateAsync(trimmed)
      toast.success(
        t('identity.saved', { defaultValue: '设备标识已保存，新推送立即生效' })
      )
    } catch (err) {
      toast.error(
        err instanceof Error
          ? err.message
          : t('identity.saveFailed', { defaultValue: '设备标识保存失败' })
      )
    }
  }

  return (
    <div className='w-full shrink-0 space-y-2 lg:w-[360px]'>
      <Label htmlFor='device-id' className='text-xs font-medium'>
        {t('identity.label', { defaultValue: '设备 ID' })}
      </Label>

      <div className='flex items-center gap-2'>
        <Input
          id='device-id'
          value={deviceId}
          maxLength={64}
          spellCheck={false}
          autoComplete='off'
          className='font-mono text-sm'
          placeholder='site-a-gate-01'
          onChange={(e) => setDeviceId(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter') {
              e.preventDefault()
              void handleSave()
            }
          }}
        />
        <Button
          type='button'
          size='sm'
          disabled={!canSave}
          onClick={() => void handleSave()}
          className='shrink-0 gap-1.5'
        >
          {updateIdentity.isPending ? (
            <Loader2 className='size-3.5 animate-spin' />
          ) : (
            <Save className='size-3.5' />
          )}
          {t('identity.save', { defaultValue: '保存' })}
        </Button>
      </div>

      <p className='text-[11px] text-muted-foreground'>
        {t('identity.hint', {
          defaultValue:
            '仅支持字母、数字、点、下划线、连字符，长度 1-64；保存后无需重启。',
        })}
      </p>
    </div>
  )
}
