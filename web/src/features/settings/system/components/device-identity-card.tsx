import { useState } from 'react'
import { Fingerprint, Loader2, Save } from 'lucide-react'
import { useTranslation } from 'react-i18next'
import { toast } from 'sonner'
import { statusTextClass } from '@/lib/status-palette'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { Skeleton } from '@/components/ui/skeleton'
import {
  useSystemIdentity,
  useUpdateSystemIdentity,
} from '../hooks/use-system-identity'
import type { SystemIdentity } from '../types'

/**
 * 设备标识配置卡片。
 *
 * 这个值会写进每一条推送出去的告警 / 识别事件（payload.device_id），
 * 是汇聚平台区分「哪台边缘主机」的唯一稳定键：主机名在刷机镜像里常常是重复的，
 * 所以这里必须允许运维手工改成现场编号。
 */
export function DeviceIdentityCard() {
  const { t } = useTranslation('system')
  const { data: identity, isLoading, error } = useSystemIdentity()

  return (
    <div className='rounded-xl border border-border/80 bg-card/75 p-4 shadow-xs backdrop-blur-md transition-all'>
      <div className='flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between'>
        <div className='flex items-start gap-3'>
          <div className='flex size-8 shrink-0 items-center justify-center rounded-lg border border-border/70 bg-muted/40 text-muted-foreground'>
            <Fingerprint className='size-4' />
          </div>
          <div className='space-y-1'>
            <div className='flex flex-wrap items-center gap-2'>
              <span className='text-sm font-semibold tracking-tight text-foreground'>
                {t('identity.title', { defaultValue: '设备标识' })}
              </span>
              {identity && (
                <Badge
                  variant={identity.autoGenerated ? 'secondary' : 'default'}
                  className='h-5 px-1.5 py-0 text-[11px] font-normal'
                >
                  {identity.autoGenerated
                    ? t('identity.autoGenerated', {
                        defaultValue: '系统自动生成',
                      })
                    : t('identity.custom', { defaultValue: '自定义' })}
                </Badge>
              )}
            </div>
            <p className='max-w-xl text-xs leading-relaxed text-muted-foreground'>
              {t('identity.desc', {
                defaultValue:
                  '该编号会写进每一条推送到 Webhook / MQTT 的事件（device_id），汇聚平台据此区分事件来自哪台边缘主机。建议改成现场编号，例如 site-a-gate-01。',
              })}
            </p>
          </div>
        </div>

        {isLoading ? (
          <Skeleton className='h-9 w-full rounded-md lg:w-[360px]' />
        ) : identity ? (
          // key 让表单在服务端值变化时重新挂载，避免在 effect 里同步 state。
          <IdentityForm key={identity.deviceId} identity={identity} />
        ) : (
          <p className='text-xs text-destructive'>
            {error instanceof Error
              ? error.message
              : t('identity.loadFailed', { defaultValue: '设备标识读取失败' })}
          </p>
        )}
      </div>
    </div>
  )
}

function IdentityForm({ identity }: { identity: SystemIdentity }) {
  const { t } = useTranslation('system')
  const updateIdentity = useUpdateSystemIdentity()
  const [deviceId, setDeviceId] = useState(identity.deviceId)

  const trimmed = deviceId.trim()
  const dirty = trimmed !== identity.deviceId
  const canSave = dirty && trimmed.length > 0 && !updateIdentity.isPending

  const handleSave = async () => {
    if (!canSave) {
      return
    }
    try {
      await updateIdentity.mutateAsync(trimmed)
      toast.success(
        t('identity.saved', { defaultValue: '设备标识已保存，新推送立即生效' })
      )
    } catch (err) {
      toast.error(
        err instanceof Error
          ? err.message
          : t('identity.saveFailed', { defaultValue: '设备标识保存失败' })
      )
    }
  }

  return (
    <div className='w-full shrink-0 space-y-1.5 lg:w-[360px]'>
      <div className='flex items-center justify-between'>
        <Label
          htmlFor='device-id'
          className='text-xs font-medium text-foreground'
        >
          {t('identity.label', { defaultValue: '设备 ID' })}
        </Label>
        {dirty && (
          <span
            className={`font-mono text-[10px] ${statusTextClass('warning')}`}
          >
            {t('identity.unsaved', { defaultValue: '* 未保存更改' })}
          </span>
        )}
      </div>

      <div className='flex items-center gap-2'>
        <Input
          id='device-id'
          value={deviceId}
          maxLength={64}
          spellCheck={false}
          autoComplete='off'
          className='h-8.5 font-mono text-xs shadow-2xs'
          placeholder='site-a-gate-01'
          onChange={(e) => setDeviceId(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter') {
              e.preventDefault()
              void handleSave()
            }
          }}
        />
        <Button
          type='button'
          size='sm'
          disabled={!canSave}
          onClick={() => void handleSave()}
          className='h-8.5 shrink-0 gap-1.5 px-3 text-xs shadow-2xs'
        >
          {updateIdentity.isPending ? (
            <Loader2 className='size-3.5 animate-spin' />
          ) : (
            <Save className='size-3.5' />
          )}
          {t('identity.save', { defaultValue: '保存' })}
        </Button>
      </div>

      <p className='text-[11px] text-muted-foreground/90'>
        {t('identity.hint', {
          defaultValue:
            '仅支持字母、数字、点、下划线、连字符，长度 1-64；保存后无需重启。',
        })}
      </p>
    </div>
  )
}
