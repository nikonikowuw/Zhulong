package logsafe

import (
	"unicode/utf8"

	"go.uber.org/zap/zapcore"
)

// SanitizingCore decorates a zapcore.Core with an always-enabled, best-effort
// structural guard. It has no production disable switch: call sites cannot opt
// out, and there is intentionally no configuration toggle.
//
// What it guarantees:
//
//   - Values of known sensitive keys (see sensitiveKeys) are replaced with
//     ValueMarker, for every zap field type.
//   - clientIp values are reduced to a masked network summary by IP.
//   - String fields and the entry message are passed through Safe, which strips
//     control characters and bounds size.
//   - ErrorType fields never expose err.Error(); only ErrorMarker/NoErrorMarker.
//   - Field types whose encoding may call application code or emit opaque
//     payloads (ObjectMarshaler, ArrayMarshaler, Reflect, Stringer, Binary,
//     Namespace and unknown types) are replaced with OmittedMarker without
//     invoking the application's marshaler/String method.
//   - With sanitizes before forwarding; Write never mutates the caller's field
//     slice; Check attaches this core so Write cannot be bypassed; Sync forwards.
//
// What it does NOT guarantee: it is not a universal secret detector. A password
// or token concatenated into an ordinary string, free-form prose, a URL query or
// an application-defined marshaler's output is not recognized. Typed helpers and
// field allowlists at the call site remain the primary controls.
//
// Entry.Stack is left untouched: it is generated by zap from program counters
// (file:line), not from caller-controlled values.
type SanitizingCore struct {
	zapcore.Core
}

var _ zapcore.Core = (*SanitizingCore)(nil)

// NewSanitizingCore wraps inner. A nil inner is replaced with a nop core so
// assembling a logger cannot panic; callers that require a real sink should
// validate before wrapping.
func NewSanitizingCore(inner zapcore.Core) *SanitizingCore {
	if inner == nil {
		inner = zapcore.NewNopCore()
	}
	return &SanitizingCore{Core: inner}
}

// Enabled reports whether the wrapped core would accept level.
func (c *SanitizingCore) Enabled(level zapcore.Level) bool { return c.Core.Enabled(level) }

// Level reports the wrapped core's minimum enabled level. zap recommends core
// wrappers implement this so zapcore.LevelOf does not have to probe Enabled for
// every level.
func (c *SanitizingCore) Level() zapcore.Level { return zapcore.LevelOf(c.Core) }

// Check attaches this wrapper to ce so the subsequent Write is sanitized. The
// wrapped core is never attached directly, which is what prevents a bypass.
func (c *SanitizingCore) Check(ent zapcore.Entry, ce *zapcore.CheckedEntry) *zapcore.CheckedEntry {
	if c.Enabled(ent.Level) {
		return ce.AddCore(ent, c)
	}
	return ce
}

// With sanitizes fields before forwarding them and returns a new wrapper around
// the wrapped core's clone.
func (c *SanitizingCore) With(fields []zapcore.Field) zapcore.Core {
	return &SanitizingCore{Core: c.Core.With(sanitizeFields(fields))}
}

// Write sanitizes the entry message and the fields, then forwards them. The
// caller's slice is copied only when a field actually needs replacing.
func (c *SanitizingCore) Write(ent zapcore.Entry, fields []zapcore.Field) error {
	ent.Message = Safe(ent.Message)
	return c.Core.Write(ent, sanitizeFields(fields))
}

// Sync forwards to the wrapped core.
func (c *SanitizingCore) Sync() error { return c.Core.Sync() }

// sensitiveKeys lists the exact normalized key names whose values must never
// reach a log sink. Matching is exact after normalization (ASCII lower-cased with
// '_', '-', '.', ':' and spaces removed). It is deliberately not a substring or
// prefix match: this core is defense in depth, so it must not pretend to
// classify names such as "db_password_hint".
//
// The switch in sensitiveKeyNormalized keeps this list and the matcher in sync;
// TestSensitiveKeyTableCoversSwitch guards that they cannot drift apart.
var sensitiveKeys = []string{
	"password",
	"passwd",
	"pwd",
	"token",
	"accesstoken",
	"refreshtoken",
	"secret",
	"clientsecret",
	"jwtsecret",
	"credential",
	"credentials",
	"authorization",
	"cookie",
	"setcookie",
	"apikey",
	"rtspurl",
	"url",
	"dsn",
	"path",
	"filepath",
	"socketpath",
}

// clientIPKey is the one key handled by a typed helper instead of a marker.
const clientIPKey = "clientip"

// maxNormalizedKeyLen bounds the stack buffer used to normalize a key.
const maxNormalizedKeyLen = 24

// sensitiveKeyNormalized reports whether normalized (already lower-cased and
// separator-free) is a sensitive key. The switch on string(buf) is allocation
// free: Go keeps a slice-to-string conversion in a comparison/switch on the
// stack.
func sensitiveKeyNormalized(normalized []byte) bool {
	switch string(normalized) {
	case "password", "passwd", "pwd",
		"token", "accesstoken", "refreshtoken",
		"secret", "clientsecret", "jwtsecret",
		"credential", "credentials",
		"authorization", "cookie", "setcookie",
		"apikey",
		"rtspurl", "url", "dsn",
		"path", "filepath", "socketpath":
		return true
	}
	return false
}

// sanitizeFields returns a copy of fields with each field sanitized. When no
// field changes, the original slice is returned so the common case allocates
// nothing.
func sanitizeFields(fields []zapcore.Field) []zapcore.Field {
	if len(fields) == 0 {
		return fields
	}
	var out []zapcore.Field
	for i, field := range fields {
		sanitized, changed := sanitizeField(field)
		if !changed {
			if out != nil {
				out = append(out, field)
			}
			continue
		}
		if out == nil {
			out = make([]zapcore.Field, i, len(fields))
			copy(out, fields[:i])
		}
		out = append(out, sanitized)
	}
	if out == nil {
		return fields
	}
	return out
}

// sanitizeField reports the sanitized field and whether it differs from field.
func sanitizeField(field zapcore.Field) (zapcore.Field, bool) {
	key := normalizeKey(field.Key)
	if sensitiveKeyNormalized(key) {
		return markerField(field.Key, ValueMarker), !isMarkerField(field, ValueMarker)
	}
	if string(key) == clientIPKey {
		masked := IPMarker
		if field.Type == zapcore.StringType {
			masked = IP(field.String)
		}
		return stringField(field.Key, masked), !isMarkerField(field, masked)
	}
	switch field.Type {
	case zapcore.ErrorType:
		summary := NoErrorMarker
		if field.Interface != nil {
			summary = ErrorMarker
		}
		return markerField(field.Key, summary), !isMarkerField(field, summary)
	case zapcore.StringType:
		safe := Safe(field.String)
		return stringField(field.Key, safe), safe != field.String
	case zapcore.ByteStringType:
		raw, ok := field.Interface.([]byte)
		if !ok {
			return markerField(field.Key, OmittedMarker), !isMarkerField(field, OmittedMarker)
		}
		safe := Safe(string(raw))
		if safe == string(raw) {
			return field, false
		}
		return stringField(field.Key, safe), true
	case zapcore.SkipType:
		return field, false
	}
	if supportedType(field.Type) {
		return field, false
	}
	return markerField(field.Key, OmittedMarker), !isMarkerField(field, OmittedMarker)
}

// supportedType reports whether a zap field type is encoded from a scalar value
// that cannot invoke application code and is already bounded in size.
func supportedType(fieldType zapcore.FieldType) bool {
	switch fieldType {
	case zapcore.BoolType,
		zapcore.Int64Type,
		zapcore.Int32Type,
		zapcore.Int16Type,
		zapcore.Int8Type,
		zapcore.Uint64Type,
		zapcore.Uint32Type,
		zapcore.Uint16Type,
		zapcore.Uint8Type,
		zapcore.UintptrType,
		zapcore.Float64Type,
		zapcore.Float32Type,
		zapcore.Complex128Type,
		zapcore.Complex64Type,
		zapcore.DurationType,
		zapcore.TimeType,
		zapcore.TimeFullType:
		return true
	default:
		return false
	}
}

// isMarkerField reports whether field already carries marker as a string value,
// so repeated sanitization (With followed by Write) stays idempotent.
func isMarkerField(field zapcore.Field, marker string) bool {
	return field.Type == zapcore.StringType && field.String == marker
}

func stringField(key, value string) zapcore.Field {
	return zapcore.Field{Key: key, Type: zapcore.StringType, String: value}
}

func markerField(key, marker string) zapcore.Field { return stringField(key, marker) }

// normalizeKey lower-cases ASCII letters and drops '_', '-', '.', ':' and
// spaces into a fixed stack buffer. Keys containing non-ASCII bytes or longer
// than maxNormalizedKeyLen return nil, which matches no sensitive key: this core
// must not guess at exotic key spellings.
func normalizeKey(key string) []byte {
	var buf [maxNormalizedKeyLen]byte
	n := 0
	for i := 0; i < len(key); i++ {
		c := key[i]
		switch c {
		case '_', '-', '.', ':', ' ':
			continue
		}
		if c >= utf8.RuneSelf {
			return nil
		}
		if c >= 'A' && c <= 'Z' {
			c += 'a' - 'A'
		}
		if n == len(buf) {
			return nil
		}
		buf[n] = c
		n++
	}
	if n == 0 {
		return nil
	}
	return buf[:n]
}
