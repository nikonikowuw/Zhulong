package systeminfo

import (
	"context"
	"strings"
	"testing"

	"github.com/nikonikowuw/Zhulong/internal/apperr"
	"github.com/nikonikowuw/Zhulong/internal/database"
	"go.uber.org/zap/zaptest"
)

func newTestIdentityDB(t *testing.T) database.DBProvider {
	t.Helper()
	dbStore := database.New(t.TempDir(), zaptest.NewLogger(t))
	if err := dbStore.OpenAndMigrate(context.Background()); err != nil {
		t.Fatalf("OpenAndMigrate: %v", err)
	}
	t.Cleanup(func() { _ = dbStore.Close() })
	return dbStore
}

func TestIdentityService_GeneratesFallbackOnFreshDatabase(t *testing.T) {
	db := newTestIdentityDB(t)
	svc := NewIdentityService(db, zaptest.NewLogger(t))

	if got := svc.DeviceID(); got != "" {
		t.Fatalf("device id must stay empty before Start, got %q", got)
	}

	if err := svc.Start(context.Background()); err != nil {
		t.Fatalf("Start: %v", err)
	}

	snapshot := svc.Snapshot()
	if !IsValidDeviceID(snapshot.DeviceID) {
		t.Fatalf("generated device id %q is not valid", snapshot.DeviceID)
	}
	if !strings.HasPrefix(snapshot.DeviceID, generatedDeviceIDPrefix) {
		t.Fatalf("generated device id %q must carry the %q prefix", snapshot.DeviceID, generatedDeviceIDPrefix)
	}
	if !snapshot.AutoGenerated {
		t.Fatal("a generated fallback must be reported as auto generated")
	}
	if snapshot.UpdatedAt.IsZero() {
		t.Fatal("generated identity must record an updated_at")
	}

	// A second service over the same database must load the same value instead of
	// generating a new one — identity has to survive restarts.
	restarted := NewIdentityService(db, zaptest.NewLogger(t))
	if err := restarted.Start(context.Background()); err != nil {
		t.Fatalf("restart Start: %v", err)
	}
	if got := restarted.DeviceID(); got != snapshot.DeviceID {
		t.Fatalf("identity changed across restart: %q != %q", got, snapshot.DeviceID)
	}
}

func TestIdentityService_UpdatePersistsAndPublishes(t *testing.T) {
	db := newTestIdentityDB(t)
	svc := NewIdentityService(db, zaptest.NewLogger(t))
	if err := svc.Start(context.Background()); err != nil {
		t.Fatalf("Start: %v", err)
	}

	updated, err := svc.Update(context.Background(), "  site-a.gate-01  ")
	if err != nil {
		t.Fatalf("Update: %v", err)
	}
	if updated.DeviceID != "site-a.gate-01" {
		t.Fatalf("expected trimmed device id, got %q", updated.DeviceID)
	}
	if updated.AutoGenerated {
		t.Fatal("operator supplied identity must not be reported as auto generated")
	}
	if got := svc.DeviceID(); got != "site-a.gate-01" {
		t.Fatalf("in-memory cache not updated, got %q", got)
	}

	reloaded := NewIdentityService(db, zaptest.NewLogger(t))
	if err := reloaded.Start(context.Background()); err != nil {
		t.Fatalf("reload Start: %v", err)
	}
	if got := reloaded.DeviceID(); got != "site-a.gate-01" {
		t.Fatalf("persisted identity not reloaded, got %q", got)
	}
	if reloaded.Snapshot().AutoGenerated {
		t.Fatal("persisted custom identity must stay non auto-generated")
	}
}

func TestIdentityService_UpdateRejectsInvalidValues(t *testing.T) {
	db := newTestIdentityDB(t)
	svc := NewIdentityService(db, zaptest.NewLogger(t))
	if err := svc.Start(context.Background()); err != nil {
		t.Fatalf("Start: %v", err)
	}
	original := svc.DeviceID()

	cases := []string{
		"",
		"   ",
		"has space",
		"-leading-hyphen",
		"slash/inside",
		"设备编号",
		strings.Repeat("a", maxDeviceIDLength+1),
	}

	for _, raw := range cases {
		if _, err := svc.Update(context.Background(), raw); err == nil {
			t.Fatalf("expected %q to be rejected", raw)
		} else if appErr, ok := err.(*apperr.Error); !ok || appErr.Code != CodeIdentityInvalid {
			t.Fatalf("expected %s, got %v", CodeIdentityInvalid, err)
		}
	}

	if got := svc.DeviceID(); got != original {
		t.Fatalf("rejected updates must not mutate the identity: %q != %q", got, original)
	}
}
